#!/usr/bin/env python3
"""Generate the cited propositions and their proof witnesses from the manifest.

    python3 tools/assumptions.py            # write ASSUMPTIONS.md
    python3 tools/assumptions.py --check    # verify it is current
"""
import pathlib, sys

try:
    import yaml
except ImportError:
    sys.exit("assumptions.py: PyYAML is required")

ROOT = pathlib.Path(__file__).resolve().parent.parent
BEGIN, END = "-- FROZEN-STATEMENT-BEGIN", "-- FROZEN-STATEMENT-END"


def frozen_block(path):
    t = (ROOT / path).read_text(encoding="utf-8")
    return t[t.index(BEGIN) + len(BEGIN):t.index(END)].strip("\n")


def render():
    man = yaml.safe_load((ROOT / "ledger" / "manifest.yaml").read_text(encoding="utf-8"))
    inputs = [n for n in man["nodes"] if n.get("state") == "FROZEN"]
    missing = [n for n in inputs if not n.get("proved_by")]
    out = ["# Literature inputs", "",
           "The following propositions record cited results used in conditional statements.",
           "Their proof status is recorded below; unconditional results apply the proofs.",
           "The verbatim frozen declarations retain their original wording.", "",
           f"Undischarged inputs at the main-result use sites: **{len(missing)}**.", "",
           "Generated by `python3 tools/assumptions.py` from `ledger/manifest.yaml`.", ""]
    for n in sorted(inputs, key=lambda x: x["id"]):
        proof = (f"* **Proved here** by `{n['proved_by']}` in `{n['proof_file']}`" + (f" (for {n['proof_scope']})" if n.get("proof_scope") else "")
                 if n.get("proved_by") else "* **Not proved here**: assumed")
        out += [f"## `{n['id']}`", "", f"* **Lean name** `{n['export']}`",
                f"* **File** `{n['file']}`", f"* **Cited at** {n['source']}", proof,
                "", "```lean", frozen_block(n["file"]), "```", ""]
    return "\n".join(out)


text = render()
target = ROOT / "ASSUMPTIONS.md"
if "--check" in sys.argv[1:]:
    cur = target.read_text(encoding="utf-8") if target.exists() else ""
    if cur != text:
        sys.exit("assumptions: ASSUMPTIONS.md is stale; rerun tools/assumptions.py")
    print("assumptions: OK (ASSUMPTIONS.md is current)")
else:
    target.write_text(text, encoding="utf-8")
    n = text.count("\n## `")
    print(f"assumptions: wrote ASSUMPTIONS.md ({n} cited input(s))")
